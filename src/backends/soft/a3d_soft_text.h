/**
 * @file a3d_soft_text.h
 * @brief A 5x7 bitmap font and a blitter, so a picture can carry a caption
 *        without linking a renderer for it.
 *
 * The glyphs were authored as ASCII art and packed by a generator, then read
 * back out and rendered to a terminal before being committed. A wrong bit in a
 * hand-written hex table is invisible; a wrong pixel in a picture of the letter
 * is not.
 *
 *
 * Column-major: one byte per column, bit 0 is the top row, five columns a
 * glyph, ASCII 32..126. 475 bytes.
 */

