/** The five column bitmaps for a character, or the '?' glyph for anything the
    font does not cover. Column `cx`, bit `cy` set means that pixel is lit.

    Exposed because a caller that wants the font at a different SIZE - repeating
    each lit pixel as an n x n block - needs the bits, and the alternative is a
    second copy of the table or a second font to keep in step with this one.
    */
inline const uint8_t* glyph5x7(char ch)
    {
    unsigned c = (unsigned char)ch;
    if ((c < 32u) || (c > 126u)) c = (unsigned)'?';
    return kFont5x7 + (c - 32u) * kFontW;
    }


/** Draw one line of text into a 16-bit framebuffer.

    `y` is the BASELINE, matching the convention the demo's overlay was written
    against. Anything outside the target is clipped per pixel rather than being
    rejected per string, so a caption may run off the edge without taking the
    rest of the line with it. */
inline void drawText5x7(uint16_t* fb, int stride, int w, int h,
                        int x, int y, const char* s, uint16_t color)
    {
    if ((fb == nullptr) || (s == nullptr)) return;
    const int top = y - (kFontH - 1);
    for (; *s != '\0'; s++, x += kFontAdvance)
        {
        const uint8_t* col = glyph5x7(*s);
        for (int cx = 0; cx < kFontW; cx++)
            {
            const int px = x + cx;
            if ((px < 0) || (px >= w)) continue;
            const uint8_t bits = col[cx];
            for (int cy = 0; cy < kFontH; cy++)
                {
                if (((bits >> cy) & 1u) == 0u) continue;
                const int py = top + cy;
                if ((py < 0) || (py >= h)) continue;
                fb[(size_t)py * stride + px] = color;
                }
            }
        }
    }

